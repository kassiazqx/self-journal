/**
 * 根据文本内容检测可能的情绪标签
 * @param {string} text
 * @returns {string[]} 匹配到的情绪标签数组
 */
export function detectEmotions(text) {
  if (!text) return []
  const matched = []
  for (const [emotion, keywords] of Object.entries(EMOTION_KEYWORD_MAP)) {
    if (keywords.some(kw => text.includes(kw))) {
      matched.push(emotion)
    }
  }
  return matched
}

